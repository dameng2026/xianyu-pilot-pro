-- 更新条件：systemPrompt 和 welcomeMessage 都匹配历史默认/遗留标记的用户才更新。
-- 历史默认标记包括：
--   systemPrompt: "你是闲鱼店铺的专业客服助手"(最早期) / "你是本店的AI客服"(早期) / "你是一个友好的闲鱼客服助手"(上一版默认)
--   welcomeMessage: "我是AI客服小鱼"(最早期) / "欢迎光临本店"(早期) / "您好，欢迎来看看这件商品"(上一版默认)
-- 若用户已自行更改过 systemPrompt 或 welcomeMessage（不包含任何上述标记），则不做处理。
UPDATE user_business_setting
SET config_json = JSON_SET(
        config_json,
        '$.systemPrompt', @new_system_prompt,
        '$.welcomeMessage', @new_welcome_message,
        '$.chatRules', @new_chat_rules
    ),
    updated_time = NOW()
WHERE setting_key = 'ai-customer-service'
  AND deleted = 0
  AND (
      JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.systemPrompt')) LIKE '%你是闲鱼店铺的专业客服助手%'
      OR JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.systemPrompt')) LIKE '%你是本店的AI客服%'
      OR JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.systemPrompt')) LIKE '%你是一个友好的闲鱼客服助手%'
  )
  AND (
      JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.welcomeMessage')) LIKE '%我是AI客服小鱼%'
      OR JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.welcomeMessage')) LIKE '%欢迎光临本店%'
      OR JSON_UNQUOTE(JSON_EXTRACT(config_json, '$.welcomeMessage')) LIKE '%您好，欢迎来看看这件商品%'
  );
